import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

// The database design is tracked in git: docs/database-schema.txt is what the app's setup code builds in schema "app".
// CI runs this against an empty Postgres (twice, so setup must be repeatable); any table, column, rule or index change
// without the matching change to that file fails the build. Locally: TEST_ACCOUNTS_DATABASE_URL=postgres://... npm test
// To accept a deliberate change: add UPDATE_SCHEMA=1 to that command and commit the file.
const url = process.env.TEST_ACCOUNTS_DATABASE_URL;
const FILE = path.join(__dirname, "..", "docs", "database-schema.txt");

async function buildAll() {
  // In production the schema is made once by hand (db/setup.sql); an empty test database needs it too.
  const { default: postgres } = await import("postgres");
  const admin = postgres(url!, { onnotice: () => {} });
  await admin`create schema if not exists app`;
  await admin.end();
  process.env.ACCOUNTS_DATABASE_URL = url;
  const { accountsSql } = await import("./accounts");
  const { seoSql } = await import("./seo/store");
  const { brokerTablesReady } = await import("./brokers/store");
  const { proTableReady } = await import("./pro");
  const { riskTablesReady } = await import("./riskPremium/store");
  const { ytmHistoryReady } = await import("./ytmHistory");
  const { weeklyTablesReady } = await import("./weeklySend");
  const { bondImportTablesReady } = await import("./bondImportDb");
  const { shortlistTablesReady } = await import("./shortlistDb");
  const sql = await accountsSql();
  await seoSql();
  await brokerTablesReady();
  await proTableReady();
  await riskTablesReady();
  await ytmHistoryReady();
  await weeklyTablesReady();
  await bondImportTablesReady();
  await shortlistTablesReady();
  return sql;
}

async function describeSchema(sql: Awaited<ReturnType<typeof buildAll>>): Promise<string> {
  const cols = await sql`
    select table_name t, column_name c, data_type d, is_nullable n, column_default x
    from information_schema.columns where table_schema = 'app' order by table_name, ordinal_position`;
  const cons = await sql`
    select conrelid::regclass::text t, conname n, pg_get_constraintdef(oid) d
    from pg_constraint where connamespace = 'app'::regnamespace order by 1, 2`;
  const idx = await sql`select tablename t, indexdef d from pg_indexes where schemaname = 'app' order by 1, 2`;
  const lines: string[] = [];
  let table = "";
  for (const r of cols) {
    if (r.t !== table) lines.push("", `table app.${(table = r.t)}`);
    const def = r.x ? ` default ${String(r.x).replace(/nextval\('[^']+'::regclass\)/, "nextval(...)")}` : "";
    lines.push(`  ${r.c} ${r.d}${r.n === "NO" ? " not null" : ""}${def}`);
  }
  lines.push("", "constraints");
  for (const r of cons) lines.push(`  ${r.t} ${r.n}: ${r.d}`);
  lines.push("", "indexes");
  for (const r of idx) lines.push(`  ${r.d}`);
  return `# Generated by lib/schema.db.test.ts from the app's setup code. Do not edit by hand.${lines.join("\n")}\n`;
}

describe.skipIf(!url)("database schema", () => {
  it("setup builds exactly the tracked schema, and running it again changes nothing", async () => {
    const sql = await buildAll();
    const first = await describeSchema(sql);
    // A second process starting against the same database must find nothing to do.
    const { setupAgainForTest } = await import("./accounts");
    await setupAgainForTest();
    const second = await describeSchema(sql);
    expect(second).toBe(first);
    if (process.env.UPDATE_SCHEMA === "1") writeFileSync(FILE, first);
    expect(first).toBe(readFileSync(FILE, "utf8"));
  }, 60_000);

  it("every table has a primary key", async () => {
    const sql = await buildAll();
    const rows = await sql`
      select c.relname t from pg_class c
      where c.relnamespace = 'app'::regnamespace and c.relkind = 'r'
        and not exists (select 1 from pg_constraint k where k.conrelid = c.oid and k.contype = 'p')`;
    expect(rows.map((r) => r.t)).toEqual([]);
  });
});

describe.skipIf(!url)("admin two-factor key on a real database", () => {
  it("is stored encrypted, still works, and an old plain key is sealed on first use", async () => {
    const sql = await buildAll();
    const { startSetup, confirmSetup, verifySecondFactor } = await import("./twoFactor");
    const { codeAt, stepOf } = await import("./totp");
    const totpAt = (s: string, t: number) => codeAt(s, stepOf(t));
    const [u] = await sql`insert into app.users (email, password_hash) values (${`2fa-${Date.now()}@test.local`}, 'x') returning id, email`;
    const user = { id: Number(u.id), email: u.email } as never;
    const { secret } = await startSetup(user);
    const [pending] = await sql`select totp_pending_secret s from app.users where id = ${u.id}`;
    expect(pending.s).not.toContain(secret);
    const t0 = Date.parse("2026-10-19T10:00:00Z");
    expect(await confirmSetup(Number(u.id), totpAt(secret, t0), t0)).toHaveLength(10);
    const [saved] = await sql`select totp_secret s from app.users where id = ${u.id}`;
    expect(saved.s.startsWith("v1:")).toBe(true);
    expect(await verifySecondFactor(Number(u.id), totpAt(secret, t0 + 60_000), t0 + 60_000)).toBe(true);
    // A key saved in plain text before this change keeps working and gets sealed.
    await sql`update app.users set totp_secret = ${secret} where id = ${u.id}`;
    expect(await verifySecondFactor(Number(u.id), totpAt(secret, t0 + 120_000), t0 + 120_000)).toBe(true);
    const [after] = await sql`select totp_secret s from app.users where id = ${u.id}`;
    expect(after.s.startsWith("v1:")).toBe(true);
  });
});

describe.skipIf(!url)("risk premium versions on a real database", () => {
  it("seeds Version 1.0 as active; a draft changes nothing until activated; recorded runs keep their version", async () => {
    const sql = await buildAll();
    const store = await import("./riskPremium/store");
    const { draftFrom } = await import("./riskPremium/versions");
    const v1 = (await store.listVersions()).find((v) => v.version === "1.0")!;
    expect(v1).toMatchObject({ status: "active", premiums: { "BBB+": 95, "AA-": 50 }, floor: "BBB-", exceptionalBp: 200, minMaturity: 4, maxMaturity: 6 });
    expect(await store.getWeight()).toBe(0);

    const version = `9.${Date.now() % 1000}`;
    const id = await store.createDraft(draftFrom(v1, { version, premiums: { "BBB+": 105 } }), null, "test draft", "test@local");
    const ev = { isin: "XS0000000001", ytm: 4.3, duration: 4.5, maturityYears: 5, rating: "BBB+", ratingSource: "S&P BBB+", requiredBp: 95, benchmarkYtm: 2.5, spreadBp: 180, riskAdjustedYtm: 3.35, surplusBp: 85, status: "eligible", reason: null, versionId: v1.id } as never;
    const run = await store.recordRun(v1.id, `test-${version}`, null, [ev], { test: true });
    expect((await store.liveRiskConfig()).curve?.premiums["BBB+"]).toBe(95);

    expect(await store.activateVersion(id, "test activation", "test@local")).toEqual([]);
    const after = await store.listVersions();
    expect(after.find((v) => v.id === v1.id)).toMatchObject({ status: "archived", premiums: { "BBB+": 95 } });
    expect(after.find((v) => v.id === id)).toMatchObject({ status: "active", premiums: { "BBB+": 105 } });
    expect(await store.updateDraft(v1.id, v1, null, "edit archived", "test@local")).toBe(false);
    const [stored] = await sql`select required_bp, version_id from app.risk_calc_results where run_id = ${run}`;
    expect([Number(stored.required_bp), Number(stored.version_id)]).toEqual([95, v1.id]);
    const audit = await store.listAudit(5);
    expect(audit.map((a) => a.action)).toContain("activate");
    // Put Version 1.0 back for anything that runs after this test.
    await sql`update app.risk_premium_versions set status = 'archived' where id = ${id}`;
    await sql`update app.risk_premium_versions set status = 'active' where id = ${v1.id}`;
  });
});
