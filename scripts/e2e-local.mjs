// Local browser check: start the standalone server on :3311 with a throwaway accounts database, then run `node scripts/e2e-local.mjs`.
import { chromium } from "playwright-core";
const BASE = "http://127.0.0.1:3311";
const SHOTS = process.env.SHOTS ?? "/tmp";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1243/chrome-linux64/chrome" });
let fails = 0;
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails++; };
const noSide = async (p, label) => ok(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${label}: no sideways scroll`);
for (const w of [1440, 390]) {
  const ctx = await browser.newContext({ viewport: { width: w, height: w === 390 ? 844 : 900 } });
  const p = await ctx.newPage();
  const errs = []; p.on("pageerror", (e) => errs.push(e.message));
  await p.goto(BASE + "/");
  await p.waitForSelector('[data-testid="cookie-banner"]');
  ok(await p.isDisabled('[data-testid="cookie-necessary"]') && await p.isChecked('[data-testid="cookie-necessary"]'), `${w} necessary always on`);
  await p.screenshot({ path: `${SHOTS}/cookie-${w}.png` });
  await p.click('[data-testid="cookie-settings"]');
  await p.click('[data-testid="cookie-statistics"]');
  await p.click('[data-testid="cookie-accept"]');
  ok(!(await p.isVisible('[data-testid="cookie-banner"]')), `${w} banner closes`);
  const stored = await p.evaluate(() => JSON.parse(localStorage.getItem("tb_cookie_consent")));
  ok(stored.statistics === true && stored.marketing === false, `${w} selection stored`);
  await p.goto(BASE + "/cookies"); // cookie settings live on the Cookies page, not in the footer
  await p.click("text=Cookie settings");
  ok(await p.isChecked('[data-testid="cookie-statistics"]'), `${w} reopened with choice`);
  await p.locator('[data-testid="cookie-statistics"]').uncheck();
  await p.locator('[data-testid="cookie-accept"]').click();
  ok(await p.evaluate(() => !localStorage.getItem("tb_vid")), `${w} deny removes visitor id`);
  await noSide(p, `${w} home`);
  const signup = async (email, user) => {
    await p.goto(BASE + "/signup");
    await p.fill("input[type=email]", email);
    await p.fill("input[autocomplete=username]", user);
    await p.fill("input[type=password]", "password123");
    await p.check("input[type=checkbox][required]");
    const t0 = Date.now();
    await p.click("button[type=submit]");
    await p.waitForSelector('[data-testid="welcome-modal"]', { timeout: 30000 });
    return Date.now() - t0;
  };
  const ms = await signup(`adm${w}@e2e.local`, `adm${w}`);
  ok(true, `${w} admin signed up with robot check in ${ms} ms`);
  await p.screenshot({ path: `${SHOTS}/welcome-${w}.png` });
  ok((await p.textContent('[data-testid="welcome-modal"]')).includes("Welcome to 10BONDS"), `${w} welcome text`);
  await p.click("text=Let’s get started!");
  ok(!(await p.isVisible('[data-testid="welcome-modal"]')), `${w} welcome closes`);
  ok(!(await p.isVisible('[data-testid="trial-badge"]')), `${w} no trial badge without a code`);
  await p.screenshot({ path: `${SHOTS}/home-in-${w}.png` });
  await noSide(p, `${w} home signed in`);
  await p.click('[data-testid="nav-admin"]');
  await p.waitForSelector('[data-testid="admin-stats"]');
  await p.fill('[data-testid="codes-count"]', "2");
  await p.click('[data-testid="codes-generate"]');
  await p.waitForSelector('[data-testid="codes-fresh"]');
  const codes = (await p.textContent('[data-testid="codes-fresh"]')).match(/10B-[A-Z2-9]{4}-[A-Z2-9]{4}/g);
  ok(codes?.length === 2, `${w} 2 codes generated`);
  await p.screenshot({ path: `${SHOTS}/admin-${w}.png`, fullPage: true });
  await noSide(p, `${w} admin`);
  await p.click("text=Sign out");
  await p.waitForURL(BASE + "/");
  await signup(`u${w}@e2e.local`, `u${w}`);
  await p.click("text=Let’s get started!");
  ok(!(await p.isVisible('[data-testid="nav-admin"]')), `${w} no Admin link for normal user`);
  const adminResp = await p.goto(BASE + "/admin");
  ok(adminResp.status() === 404, `${w} /admin is 404 for normal user`);
  ok((await p.request.get(BASE + "/api/admin/codes")).status() === 404, `${w} admin API 404 for normal user`);
  await p.goto(BASE + "/redeem");
  await p.fill('[data-testid="redeem-code"]', codes[0].toLowerCase());
  await p.click("button:has-text('Redeem')");
  await p.waitForSelector('[data-testid="redeem-msg"]');
  ok((await p.textContent('[data-testid="redeem-msg"]')).startsWith("Done!"), `${w} code redeemed`);
  await p.click("button:has-text('Redeem')");
  await p.waitForFunction(() => document.querySelector('[data-testid="redeem-msg"]')?.textContent.includes("already"));
  ok(true, `${w} reuse refused`);
  await noSide(p, `${w} redeem`);
  ok(errs.length === 0, `${w} no page errors ${errs.join(" | ")}`);
  await ctx.close();
}
const r1 = await fetch(BASE + "/api/auth/signup", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email: "bot@e2e.local", username: "botbot", password: "password123", acceptTerms: true }) });
ok(r1.status === 400, "signup without robot check refused");
await browser.close();
console.log(fails ? `${fails} FAILED` : "ALL PASSED");
process.exit(fails ? 1 : 0);
