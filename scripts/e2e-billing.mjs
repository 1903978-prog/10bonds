// Local billing check: stripe-mock.mjs on :3312, the standalone server on :3311 with STRIPE_SECRET_KEY=sk_test_local
// and STRIPE_API_BASE=http://127.0.0.1:3312, then `node scripts/e2e-billing.mjs`.
import { createHmac } from "node:crypto";
import { chromium } from "playwright-core";
const BASE = "http://127.0.0.1:3311", MOCK = "http://127.0.0.1:3312";
const SHOTS = process.env.SHOTS ?? "/tmp";
const KEY = { Authorization: "Bearer sk_test_local" };
let fails = 0;
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails++; };
const mock = async () => (await fetch(MOCK + "/__state", { headers: KEY })).json();
const hook = async (event, secret, sigOverride) => {
  const body = JSON.stringify(event), t = Math.floor(Date.now() / 1000);
  const sig = sigOverride ?? `t=${t},v1=${createHmac("sha256", secret).update(`${t}.${body}`).digest("hex")}`;
  return fetch(BASE + "/api/stripe/webhook", { method: "POST", body, headers: { "stripe-signature": sig, "Content-Type": "application/json" } });
};
const health = await (await fetch(BASE + "/api/health/billing")).json();
ok(health.configured && health.prices === 6 && health.portal && health.webhook, `billing health ${JSON.stringify(health)}`);
let st = await mock();
ok(st.prices.length === 6 && st.prices.every((p) => p.currency === "eur"), "six EUR prices created");
ok(st.prices.map((p) => p.unit_amount).sort((a, b) => a - b).join() === "900,1900,8640,8900,18240,85440", "amounts: 9, 19, 89 a month and 86.40, 182.40, 854.40 a year");
ok(st.webhooks.length === 1 && st.webhooks[0].url.endsWith("/api/stripe/webhook"), "one webhook endpoint created");
const secret = st.webhooks[0].secret;
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1243/chrome-linux64/chrome" });
for (const w of [1440, 390]) {
  const ctx = await browser.newContext({ viewport: { width: w, height: w === 390 ? 844 : 900 } });
  const p = await ctx.newPage();
  const errs = []; p.on("pageerror", (e) => errs.push(e.message));
  await p.addInitScript(() => localStorage.setItem("tb_cookie_consent", JSON.stringify({ necessary: true, preferences: false, statistics: false, marketing: false })));
  await p.goto(BASE + "/pricing");
  ok(await p.isVisible("text=Create a free account first"), `${w} signed out: paid plans ask for an account`);
  const email = `pay${w}${Date.now() % 100000}@e2e.local`;
  await p.goto(BASE + "/signup");
  await p.fill("input[type=email]", email);
  await p.fill("input[autocomplete=username]", `pay${w}${Date.now() % 100000}`);
  await p.fill("input[type=password]", "password123");
  await p.check("input[type=checkbox][required]");
  await p.click("button[type=submit]");
  await p.waitForSelector('[data-testid="welcome-modal"]', { timeout: 30000 });
  await p.goto(BASE + "/pricing");
  ok(await p.isDisabled('[data-testid="buy-plus"]'), `${w} buy button waits for the start-now tick`);
  await p.screenshot({ path: `${SHOTS}/pricing-${w}.png`, fullPage: true });
  ok(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${w} no sideways scroll`);
  await p.check('[data-testid="start-now-plus"]');
  await Promise.all([p.waitForURL(/3312\/pay\//), p.click('[data-testid="buy-plus"]')]);
  ok(true, `${w} redirected to checkout`);
  st = await mock();
  const sess = st.sessions.at(-1), plusPrice = st.prices.find((x) => x.lookup_key.includes("plus"));
  ok(sess.price === plusPrice.id && sess.customer && sess.user_id, `${w} checkout for the Plus price with customer and user id`);
  const subId = `sub_${w}`;
  const subObj = (status, lk, extra = {}) => ({ id: subId, object: "subscription", customer: sess.customer, status, metadata: { user_id: sess.user_id }, cancel_at_period_end: false, current_period_end: Math.floor(Date.now() / 1000) + 30 * 86400, items: { data: [{ price: { id: "x", lookup_key: lk } }] }, ...extra });
  await fetch(MOCK + "/__sub", { method: "POST", headers: KEY, body: new URLSearchParams({ json: JSON.stringify(subObj("active", "tenbonds_plus_monthly_eur")) }) });
  const bad = await hook({ type: "checkout.session.completed", data: { object: { subscription: subId } } }, secret, "t=1,v1=00");
  ok(bad.status === 400, `${w} unsigned webhook refused (${bad.status})`);
  const r = await hook({ type: "checkout.session.completed", data: { object: { subscription: subId } } }, secret);
  ok(r.status === 200, `${w} signed webhook accepted`);
  const me = async () => { if (!p.url().startsWith(BASE)) await p.goto(BASE + "/pricing"); return p.evaluate(async () => (await fetch("/api/auth/me")).json()); };
  let u = await me();
  ok(u.storedPlan === "plus" && u.subscription?.status === "active", `${w} plan stored as plus (${u.storedPlan})`);
  await p.goto(BASE + "/pricing?paid=1");
  ok(await p.isVisible('[data-testid="paid-msg"]'), `${w} thank-you shown`);
  await p.screenshot({ path: `${SHOTS}/pricing-paid-${w}.png`, fullPage: true });
  await p.goto(BASE + "/account");
  await Promise.all([p.waitForURL(/3312\/portal\//), p.click('[data-testid="manage-subscription"]')]);
  ok((await mock()).portalSessions.at(-1).customer === sess.customer, `${w} portal opened for the same customer`);
  await p.goto(BASE + "/pricing");
  const again = await p.evaluate(async () => (await fetch("/api/billing/checkout", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ plan: "premium", startNow: true }) })).status);
  ok(again === 409, `${w} second subscription refused (${again})`);
  await hook({ type: "customer.subscription.updated", data: { object: subObj("active", "tenbonds_premium_monthly_eur") } }, secret);
  ok((await me()).storedPlan === "premium", `${w} switch to Premium follows`);
  await hook({ type: "customer.subscription.deleted", data: { object: { ...subObj("canceled", "tenbonds_premium_monthly_eur"), id: "sub_old" } } }, secret);
  ok((await me()).storedPlan === "premium", `${w} an old subscription ending does not cancel the live one`);
  await hook({ type: "customer.subscription.deleted", data: { object: subObj("canceled", "tenbonds_premium_monthly_eur") } }, secret);
  u = await me();
  ok(u.storedPlan === "free", `${w} cancelled subscription goes back to free`);
  ok(errs.length === 0, `${w} no page errors ${errs.join(" | ")}`);
  await ctx.close();
}
await browser.close();
console.log(fails ? `${fails} FAILED` : "ALL PASSED");
process.exit(fails ? 1 : 0);
